const byId = new Map(RESOURCES.map((r) => [r.id, r]));

export function getResource(id: string): Resource | undefined {
  return byId.get(id);
}

export function resourcesForTopic(topicId: string, subject?: string): Resource[] {
  const exact = RESOURCES.filter((r) => r.topicTags.includes(topicId));
  const broad = subject
    ? RESOURCES.filter((r) => !r.topicTags.includes(topicId) && r.subjects.includes(subject as Resource["subjects"][number]) && r.kind !== "videolezione" && r.access === "free")
    : [];
  return [...exact, ...broad.slice(0, 4)];
}
