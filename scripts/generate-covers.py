#!/usr/bin/env python3
"""Generate the illustrated covers of the resources with an OpenAI image model (ChatGPT).

Only resources that publish no usable official image are covered (see
scripts/cover-prompts.json). The images are illustrations: the app labels them as
AI-generated and never as official course material.

Usage (the key is read from the environment, never from the command line):
    OPENAI_API_KEY=... python3 scripts/generate-covers.py            # missing covers only
    python3 scripts/generate-covers.py --only mit-703,khan-chem --force
    python3 scripts/generate-covers.py --dry-run                     # print the prompts
Optional: OPENAI_IMAGE_MODEL (default gpt-image-1).

Writes public/images/covers/<id>-1536.webp and <id>-640.webp, then regenerates
src/data/generated-covers.ts from the files actually present.
"""

import argparse
import base64
import io
import json
import os
import sys
import urllib.error
import urllib.request

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROMPTS = os.path.join(ROOT, "scripts", "cover-prompts.json")
OUT_DIR = os.path.join(ROOT, "public", "images", "covers")
DATA_FILE = os.path.join(ROOT, "src", "data", "generated-covers.ts")
API_URL = "https://api.openai.com/v1/images/generations"
SIZES = ((1536, 82), (640, 80))


def build_prompt(spec, cover):
    accent = spec["accents"][cover["accent"]]
    return f'{cover["motif"][0].upper()}{cover["motif"][1:]}. {spec["style"].format(accent=accent)}'


def generate(prompt, model, key):
    body = json.dumps({"model": model, "prompt": prompt, "size": "1536x1024", "quality": "high", "n": 1}).encode()
    req = urllib.request.Request(API_URL, data=body, headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=300) as res:
            payload = json.load(res)
    except urllib.error.HTTPError as err:
        detail = err.read().decode(errors="replace")[:500]
        raise RuntimeError(f"HTTP {err.code}: {detail}") from None
    item = payload["data"][0]
    if "b64_json" not in item:
        raise RuntimeError("the response has no b64_json image (use a gpt-image model)")
    return Image.open(io.BytesIO(base64.b64decode(item["b64_json"]))).convert("RGB")


def save(image, cover_id):
    os.makedirs(OUT_DIR, exist_ok=True)
    for width, quality in SIZES:
        resized = image.resize((width, round(image.height * width / image.width)), Image.LANCZOS)
        resized.save(os.path.join(OUT_DIR, f"{cover_id}-{width}.webp"), "WEBP", quality=quality, method=6)


def write_data(spec):
    entries = []
    for cover in spec["covers"]:
        big = os.path.join(OUT_DIR, f'{cover["id"]}-1536.webp')
        small = os.path.join(OUT_DIR, f'{cover["id"]}-640.webp')
        if os.path.exists(big) and os.path.exists(small):
            width, height = Image.open(big).size
            entries.append(f'  {json.dumps(cover["id"])}: {{ alt: {json.dumps(cover["alt"], ensure_ascii=False)}, width: {width}, height: {height} }},')
    head = "export const GENERATED_COVERS: Record<string, { alt: string; width: number; height: number }> = {"
    lines = [
        "// Generated by scripts/generate-covers.py from the files in public/images/covers. Do not edit by hand.",
        "// AI-generated illustrations for resources without a usable official image (never official material).",
        "",
        *([head, *entries, "};"] if entries else [head + "};"]),
        "",
    ]
    with open(DATA_FILE, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return len(entries)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", help="comma-separated resource ids")
    parser.add_argument("--force", action="store_true", help="regenerate covers that already exist")
    parser.add_argument("--dry-run", action="store_true", help="print the prompts and exit")
    args = parser.parse_args()

    with open(PROMPTS, encoding="utf-8") as fh:
        spec = json.load(fh)
    covers = spec["covers"]
    if args.only:
        wanted = {x.strip() for x in args.only.split(",") if x.strip()}
        covers = [c for c in covers if c["id"] in wanted]

    if args.dry_run:
        for cover in covers:
            print(f'{cover["id"]}:\n  {build_prompt(spec, cover)}\n')
        return 0

    key = os.environ.get("OPENAI_API_KEY")
    if not key:
        print("OPENAI_API_KEY is not set: add it to the environment and run again.", file=sys.stderr)
        return 2
    model = os.environ.get("OPENAI_IMAGE_MODEL", "gpt-image-1")

    failures = 0
    for cover in covers:
        target = os.path.join(OUT_DIR, f'{cover["id"]}-1536.webp')
        if os.path.exists(target) and not args.force:
            print(f'skip {cover["id"]} (exists)')
            continue
        try:
            save(generate(build_prompt(spec, cover), model, key), cover["id"])
            print(f'ok   {cover["id"]}')
        except Exception as err:  # keep going: one failed cover must not stop the others
            failures += 1
            print(f'FAIL {cover["id"]}: {err}', file=sys.stderr)

    count = write_data(spec)
    print(f"{count} covers listed in src/data/generated-covers.ts; {failures} failed.")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
